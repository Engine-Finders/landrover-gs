import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/landrover-trade-fleet-engines.json";

const PATH = "/landrover-trade-fleet-engines";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Trade & Fleet Engine Services | Land Rover Garage",
  description: "Professional Land Rover engine rebuild, replacement and reconditioning services for trade customers, commercial fleets and B2B partners. Nationwide coverage. Get a quote today.",
  alternates: { canonical: PATH },
};

export default function LandRoverTradeFleetEngineServicesPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
