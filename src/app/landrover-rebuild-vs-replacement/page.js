import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/landrover-rebuild-vs-replacement.json";

const PATH = "/landrover-rebuild-vs-replacement";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Rebuild vs Replacement | Land Rover Garage",
  description: "Compare Land Rover engine rebuild vs replacement: costs, process, vehicle value, warranty. Expert advice to help you decide which is right for your vehicle.",
  alternates: { canonical: PATH },
};

export default function LandRoverRebuildVsReplacementPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
