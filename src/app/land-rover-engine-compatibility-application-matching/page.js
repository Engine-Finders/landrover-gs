import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/land-rover-engine-compatibility-application-matching.json";

const PATH = "/land-rover-engine-compatibility-application-matching";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Engine Compatibility & Application Matching | Land Rover Garage",
  description: "Precision engine matching for your Land Rover. We verify every engine against your VIN, chassis, model year, and ECU calibration. Get the exact fit, every time.",
  alternates: { canonical: PATH },
};

export default function LandRoverEngineCompatibilityApplicationMatchingPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
