import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/land-rover-cylinder-head-repair-rebuild.json";

const PATH = "/land-rover-cylinder-head-repair-rebuild";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Cylinder Head Repair & Rebuild | Land Rover Garage",
  description: "Professional cylinder head overhaul for Land Rover engines — crack testing, pressure testing, resurfacing, valve guides, valve seats, and full top-end rebuild.",
  alternates: { canonical: PATH },
};

export default function LandRoverCylinderHeadRepairRebuildPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
