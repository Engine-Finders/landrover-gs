import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/land-rover-engine-inspection-assessment.json";

const PATH = "/land-rover-engine-inspection-assessment";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Engine Inspection & Assessment | Land Rover Garage",
  description: "Professional Land Rover engine inspection and assessment at our Essex workshop. Diagnostic scan, compression tests, borescope inspection and detailed reporting.",
  alternates: { canonical: PATH },
};

export default function LandRoverEngineInspectionAssessmentPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
