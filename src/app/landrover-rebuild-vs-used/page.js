import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/landrover-rebuild-vs-used.json";

const PATH = "/landrover-rebuild-vs-used";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Rebuild vs Used Engine | Land Rover Garage",
  description: "Compare Land Rover engine rebuild vs used engine: costs, risks, process differences and decision factors. Expert advice from Land Rover Garage specialists.",
  alternates: { canonical: PATH },
};

export default function LandRoverRebuildVsUsedEnginePage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
