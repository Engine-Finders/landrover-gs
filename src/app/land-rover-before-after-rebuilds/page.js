import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/land-rover-before-after-rebuilds.json";

const PATH = "/land-rover-before-after-rebuilds";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Land Rover Before & After Rebuilds | Land Rover Garage",
  description: "See real Land Rover engine rebuild transformations at our Essex workshop. Before and after photos of TDV6, SDV6, Ingenium, and AJ-V8 engine rebuilds.",
  alternates: { canonical: PATH },
};

export default function LandRoverBeforeAfterRebuildsPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
